#!/usr/bin/env python3
# Writes the VSTM/VLDM jump tables VFPSupport.s includes:
#   gen-tables.py DIR  ->  DIR/tables-save.inc, DIR/tables-load.inc
# For n = 1..32 registers, entry n-1 (3 instructions) stores or loads
# D0..D(n-1) at r3, then branches to save_done / load_done.
import sys

for op, name in (("vstmia", "save"), ("vldmia", "load")):
    out = []
    for n in range(1, 33):
        if n <= 16:
            regs = "d0" if n == 1 else f"d0-d{n - 1}"
            out += [f"\t{op}\tr3, {{{regs}}}", f"\tb\t{name}_done", "\tnop"]
        else:
            regs = "d16" if n == 17 else f"d16-d{n - 1}"
            out += [f"\t{op}\tr3!, {{d0-d15}}", f"\t{op}\tr3, {{{regs}}}",
                    f"\tb\t{name}_done"]
    with open(f"{sys.argv[1]}/tables-{name}.inc", "w") as f:
        f.write("@ Generated by gen-tables.py\n" + "\n".join(out) + "\n")
