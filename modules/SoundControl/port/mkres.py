#!/usr/bin/env python3
"""mkres.py NAME MESSAGES CMDHELP OUT.inc: a ResourceFS file block (for
ResourceFS_RegisterFiles) holding Resources.NAME.Messages: ROOL's Messages
with the *Help texts (CmdHelp, if not "-") appended, as ROOL's build does."""
import sys
name_, msgs_f, help_f, out_f = sys.argv[1:5]
msgs = open(msgs_f, 'rb').read()
help_ = b'' if help_f == '-' else b''.join(
    l for l in open(help_f, 'rb').read().splitlines(True) if not l.startswith(b'#'))
data = msgs + (b'' if msgs.endswith(b'\n') else b'\n') + help_
name = b'Resources.' + name_.encode() + b'.Messages\0'
name += b'\0' * (-len(name) % 4)
pad = data + b'\0' * (-len(data) % 4)
entry = 4 * 5 + len(name) + 4 + len(pad)
out = ['@ generated by mkres.py: do not edit']
out.append('\t.word\t%d\t\t\t@ offset to the next file' % entry)
out.append('\t.word\t0xFFFFFF00, 0, %d, 3\t@ load (type &FFF), exec, length, attributes' % len(data))
out.append('\t.byte\t' + ', '.join(str(b) for b in name))
out.append('\t.word\t%d' % (len(data) + 4))
for i in range(0, len(pad), 16):
    out.append('\t.byte\t' + ', '.join(str(b) for b in pad[i:i + 16]))
out.append('\t.word\t0\t\t\t@ end of the files')
open(out_f, 'w').write('\n'.join(out) + '\n')
