#!/usr/bin/env python3
"""Generates tests/programs/t_neonint.c: every NEON integer instruction the
testbed's QEMU runs through its whole-instruction helpers (and the
immediate forms with every shift count), on edge-heavy random inputs,
hashing the results and the FPSCR QC flag. Run it with RISCOS_NO_HOSTNEON=1
and without: the output must be the same."""
import sys

ins = []          # (name, C body)
def long3(op, dt, kind):
    # kind: 'q,d,d' 'q,q,d' accumulate etc
    if kind == 'w':
        asm = f'"{op}.{dt} %q0, %q1, %P2" : "=w"(r) : "w"(a), "w"(lo(b))'
    elif kind == 'acc':
        asm = f'"{op}.{dt} %q0, %P1, %P2" : "+w"(r) : "w"(lo(a)), "w"(lo(b))'
    else:
        asm = f'"{op}.{dt} %q0, %P1, %P2" : "=w"(r) : "w"(lo(a)), "w"(lo(b))'
    ins.append((f'{op}.{dt}', 2, asm))

for dt in ('s8', 'u8', 's16', 'u16', 's32', 'u32'):
    for op in ('vaddl', 'vsubl', 'vabdl', 'vmull'):
        long3(op, dt, 'l')
    for op in ('vaddw', 'vsubw'):
        long3(op, dt, 'w')
    for op in ('vabal', 'vmlal', 'vmlsl'):
        long3(op, dt, 'acc')

for op, dts in (('vshrn', ('i16', 'i32')), ('vrshrn', ('i16', 'i32')),
                ('vqshrun', ('s16', 's32')), ('vqrshrun', ('s16', 's32')),
                ('vqshrn', ('s16', 'u16', 's32', 'u32')),
                ('vqrshrn', ('s16', 'u16', 's32', 'u32'))):
    for dt in dts:
        w = int(dt[1:])
        for sh in range(1, w // 2 + 1):
            ins.append((f'{op}.{dt} #{sh}', 1,
                        f'"{op}.{dt} %P0, %q1, #{sh}" : "=w"(rd) : "w"(a)'))

for dt in ('s8', 'u8', 's16', 'u16'):
    w = int(dt[1:])
    for sh in range(0, w):
        name = 'vmovl' if sh == 0 else 'vshll'
        asm = (f'"vmovl.{dt} %q0, %P1" : "=w"(r) : "w"(lo(a))' if sh == 0 else
               f'"vshll.{dt} %q0, %P1, #{sh}" : "=w"(r) : "w"(lo(a))')
        ins.append((f'{name}.{dt}' + (f' #{sh}' if sh else ''), 1, asm))

for op in ('vmul', 'vmla', 'vmls'):
    for q in (0, 1):
        for lane in range(4):
            con = '"+w"' if op != 'vmul' else '"=w"'
            if q:
                asm = f'"{op}.i16 %q0, %q1, %P2[{lane}]" : {con}(r) : "w"(a), "x"(lo(b))'
            else:
                asm = f'"{op}.i16 %P0, %P1, %P2[{lane}]" : {con}(rd) : "w"(lo(a)), "x"(lo(b))'
            ins.append((f'{op}.i16 {"q" if q else "d"} [{lane}]', 2, asm))
        # .i32 by scalar goes through QEMU's own inline code: a reference
        asm = f'"{op}.i32 %q0, %q1, %P2[1]" : "{"+w" if op != "vmul" else "=w"}"(r) : "w"(a), "x"(lo(b))'
        ins.append((f'{op}.i32 q [1]', 2, asm))

out = ['''/* t_neonint: generated by tests/gen-neonint.py - do not edit.
   NEON integer instructions on edge-heavy inputs; one CRC per instruction
   (results and the QC flag). Copyright 2026 Andrew Youll. MIT licence. */
#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include <arm_neon.h>

#define NV 40
static uint8_t vals[NV][16];
static uint32_t crc_tab[256];

static void crc_init (void)
{
  for (uint32_t i = 0; i < 256; i++)
    {
      uint32_t c = i;
      for (int k = 0; k < 8; k++)
        c = c & 1 ? 0xedb88320 ^ (c >> 1) : c >> 1;
      crc_tab[i] = c;
    }
}

static uint32_t crc_bytes (uint32_t c, const void *p, int n)
{
  const uint8_t *b = p;
  while (n--)
    c = crc_tab[(c ^ *b++) & 0xff] ^ (c >> 8);
  return c;
}

static uint32_t rs = 0x9E3779B9;
static uint32_t rnd (void)
{
  rs ^= rs << 13, rs ^= rs >> 17, rs ^= rs << 5;
  return rs;
}

static void make_values (void)
{
  static const uint8_t edge[] = { 0x00, 0x01, 0x7f, 0x80, 0x81, 0xfe, 0xff, 0x40 };
  for (int v = 0; v < NV; v++)
    for (int i = 0; i < 16; i++)
      {
        uint32_t r = rnd ();
        vals[v][i] = v < 8 ? edge[v] : (r & 3) ? (uint8_t) (r >> 8) : edge[(r >> 2) & 7];
      }
}

static inline void set_fpscr (uint32_t v)
{
  __asm__ volatile ("vmsr fpscr, %0" : : "r" (v) : "memory");
}

static inline uint32_t get_fpscr (void)
{
  uint32_t v;
  __asm__ volatile ("vmrs %0, fpscr" : "=r" (v) : : "memory");
  return v;
}

#define lo(x) vget_low_u8 (x)
''']
for k, (name, ar, asm) in enumerate(ins):
    out.append(f'''static uint32_t t{k} (uint32_t crc, int i, int j)
{{
  uint8x16_t a = vld1q_u8 (vals[i]), b = vld1q_u8 (vals[j]);
  uint8x16_t r = vld1q_u8 (vals[(i + j + 1) % NV]);
  uint8x8_t rd = vget_low_u8 (r);
  (void) b;
  set_fpscr (0);
  __asm__ volatile ({asm});
  uint8_t o[16];
  vst1q_u8 (o, r);
  vst1_u8 (o, rd);
  uint32_t f = get_fpscr () >> 27 & 1;
  crc = crc_bytes (crc, o, 16);
  return crc_bytes (crc, &f, 1);
}}
''')
out.append('static const struct { const char *name; int arity; uint32_t (*fn) (uint32_t, int, int); } tests[] = {')
for k, (name, ar, asm) in enumerate(ins):
    out.append(f'  {{"{name}", {ar}, t{k}}},')
out.append('''};

int
main (void)
{
  crc_init ();
  make_values ();
  uint32_t all = 0xffffffff;
  for (size_t t = 0; t < sizeof tests / sizeof tests[0]; t++)
    {
      uint32_t c = 0xffffffff;
      for (int i = 0; i < NV; i++)
        for (int j = 0; j < (tests[t].arity == 2 ? NV : 1); j++)
          c = tests[t].fn (c, i, j);
      printf ("%-22s %08x\\n", tests[t].name, ~c);
      all = crc_bytes (all, &c, 4);
    }
  printf ("t_neonint: %u instructions, CRC %08x\\n",
          (unsigned) (sizeof tests / sizeof tests[0]), ~all);
  return 0;
}
''')
open(sys.argv[1], 'w').write('\n'.join(out))
