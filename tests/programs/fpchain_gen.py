#!/usr/bin/env python3
# fpchain_gen.py SEED NBLOCKS LEN > t_fpchain_blocks.h (made with 2026 12 48;
# t_fpchain_long_blocks.h with 77 3 450)
# Straight-line blocks of VFP and NEON floating point instructions for
# t_fpchain.c: each block is a C function body of inline assembly working
# on d0-d31 (loaded from and stored to memory around it).
import random, sys
seed, nblocks, length = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3])
R = random.Random(seed)
S = lambda: "s%d" % R.randrange(32)
D = lambda: "d%d" % R.randrange(32)
Dlo = lambda: "d%d" % R.randrange(16)            # by-scalar operand: d0-d15
Q = lambda: "q%d" % R.randrange(16)
conds = ["eq", "ne", "gt", "ge", "lt", "le", "mi", "pl", "vs", "vc", "hi", "ls"]
def one():
    k = R.randrange(100)
    if k < 30:
        op = R.choice(["vadd", "vsub", "vmul", "vdiv", "vnmul", "vmla", "vmls", "vnmla", "vnmls"])
        if R.random() < 0.5:
            return ["%s.f32 %s, %s, %s" % (op, S(), S(), S())]
        return ["%s.f64 %s, %s, %s" % (op, D(), D(), D())]
    if k < 38:
        op = R.choice(["vsqrt", "vabs", "vneg", "vmov"])
        if R.random() < 0.5:
            return ["%s.f32 %s, %s" % (op, S(), S())]
        return ["%s.f64 %s, %s" % (op, D(), D())]
    if k < 48:
        c = R.choice(["vcvt.f64.f32 %s, %s" % (D(), S()), "vcvt.f32.f64 %s, %s" % (S(), D()),
                      "vcvt.s32.f32 %s, %s" % (S(), S()), "vcvt.u32.f32 %s, %s" % (S(), S()),
                      "vcvt.f32.s32 %s, %s" % (S(), S()), "vcvt.f32.u32 %s, %s" % (S(), S()),
                      "vcvt.s32.f64 %s, %s" % (S(), D()), "vcvt.u32.f64 %s, %s" % (S(), D()),
                      "vcvt.f64.s32 %s, %s" % (D(), S()), "vcvt.f64.u32 %s, %s" % (D(), S()),
                      "vcvtr.s32.f32 %s, %s" % (S(), S())])
        return [c]
    if k < 56:
        # compare, flags to APSR, then a conditional instruction (IT in Thumb)
        c = R.choice(conds)
        if R.random() < 0.5:
            cmp = "%s.f32 %s, %s" % (R.choice(["vcmp", "vcmpe"]), S(), S() if R.random() < 0.8 else "#0")
            then = "%s%s.f32 %s, %s, %s" % (R.choice(["vadd", "vmul", "vsub", "vmla"]), c, S(), S(), S())
        else:
            cmp = "%s.f64 %s, %s" % (R.choice(["vcmp", "vcmpe"]), D(), D() if R.random() < 0.8 else "#0")
            then = "%s%s.f64 %s, %s, %s" % (R.choice(["vadd", "vmul", "vsub", "vmla"]), c, D(), D(), D())
        return [cmp, "vmrs APSR_nzcv, fpscr", "IT %s" % c, then]
    if k < 80:
        op = R.choice(["vadd", "vsub", "vmul", "vmla", "vmls", "vmax", "vmin", "vabd",
                       "vceq", "vcge", "vcgt", "vacge", "vacgt"])
        if R.random() < 0.7:
            return ["%s.f32 %s, %s, %s" % (op, Q(), Q(), Q())]
        return ["%s.f32 %s, %s, %s" % (op, D(), D(), D())]
    if k < 88:
        op = R.choice(["vmul", "vmla", "vmls"])
        reg = Q() if R.random() < 0.7 else D()
        return ["%s.f32 %s, %s, %s[%d]" % (op, reg, Q() if reg[0] == "q" else D(), Dlo(), R.randrange(2))]
    if k < 94:
        op = R.choice(["vceq", "vcge", "vcgt", "vcle", "vclt"])
        return ["%s.f32 %s, %s, #0" % (op, Q(), Q())]
    op = R.choice(["vcvt.s32.f32", "vcvt.u32.f32", "vcvt.f32.s32", "vcvt.f32.u32"])
    return ["%s %s, %s" % (op, Q(), Q())]
print("/* generated by fpchain_gen.py %d %d %d */" % (seed, nblocks, length))
for b in range(nblocks):
    lines = []
    while len(lines) < length:
        lines += one()
    print("#define BLOCK%d \\" % b)
    for l in lines:
        if l.startswith("IT "):
            print('  IT_(%s) \\' % l.split()[1])
        else:
            print('  "%s\\n\\t" \\' % l)
    print("")
print("#define NBLOCKS %d" % nblocks)
print("#define BLOCKS(X) " + " ".join("X(%d)" % b for b in range(nblocks)))
