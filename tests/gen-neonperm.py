#!/usr/bin/env python3
# gen-neonperm.py: writes tests/programs/t_neonperm.c, a conformance test
# for the Neon permutes and structure loads and stores that the test bed's
# QEMU does as host vector instructions (VZIP, VUZP; VLD2/VLD4, VST2/VST4 of
# 8 and 16 bits): one CRC per instruction form over the registers it
# changes, the memory it writes and the base register's write-back, at
# several alignments. The CRCs must be the same with the host vector code
# and with QEMU's own (RISCOS_NO_HOSTNEON=1).
#
# Copyright (c) 2026 Andrew Youll. MIT licence (see LICENSE).
import os

out = []
w = out.append

w('''/* t_neonperm: generated by tests/gen-neonperm.py - do not edit.
   Neon permutes (VZIP, VUZP) and structure loads and stores (VLD2/4,
   VST2/4 of 8 and 16 bits): one CRC per form, over the registers, the
   memory written and the write-back. Copyright 2026 Andrew Youll. MIT
   licence. */
#include <stdio.h>
#include <stdint.h>
#include <string.h>

static uint32_t crc_tab[256];
static void crc_init (void)
{
  for (uint32_t i = 0; i < 256; i++)
    {
      uint32_t c = i;
      for (int k = 0; k < 8; k++)
        c = c & 1 ? 0xedb88320 ^ (c >> 1) : c >> 1;
      crc_tab[i] = c;
    }
}
static uint32_t crc_bytes (uint32_t c, const void *p, int n)
{
  const uint8_t *b = p;
  while (n--)
    c = crc_tab[(c ^ *b++) & 0xff] ^ (c >> 8);
  return c;
}

/* registers d16-d23 in and out (64 bytes); memory to load from and store to */
static uint8_t regs_in[64] __attribute__ ((aligned (32)));
static uint8_t regs_out[64] __attribute__ ((aligned (32)));
static uint8_t src[160] __attribute__ ((aligned (32)));
static uint8_t dst[160] __attribute__ ((aligned (32)));

static void fill (uint32_t seed)
{
  uint32_t s = seed * 2654435761u + 1;
  for (int i = 0; i < 64; i++)
    {
      s ^= s << 13, s ^= s >> 17, s ^= s << 5;
      regs_in[i] = s >> 7;
    }
  for (int i = 0; i < 160; i++)
    {
      s ^= s << 13, s ^= s >> 17, s ^= s << 5;
      src[i] = s >> 11;
      dst[i] = 0xa5;
    }
}

#define LOAD_REGS "vld1.8 {d16-d19}, [%[ri]]!\\n\\tvld1.8 {d20-d23}, [%[ri]]\\n\\t"
#define SAVE_REGS "\\n\\tvst1.8 {d16-d19}, [%[ro]]!\\n\\tvst1.8 {d20-d23}, [%[ro]]"
#define CLOBBERS "d16", "d17", "d18", "d19", "d20", "d21", "d22", "d23", "memory"
''')

tests = []

# permutes
perms = []
for op in ('vzip', 'vuzp'):
    for sz in ('8', '16'):
        perms.append(f'{op}.{sz} d16, d17')
        perms.append(f'{op}.{sz} d19, d16')
    for sz in ('8', '16', '32'):
        perms.append(f'{op}.{sz} q8, q9')
        perms.append(f'{op}.{sz} q11, q8')

for i, insn in enumerate(perms):
    name = f'perm{i}'
    w(f'''
static uint32_t {name} (void)
{{
  uint32_t c = 0;
  for (int k = 0; k < 6; k++)
    {{
      uint8_t *ri = regs_in, *ro = regs_out;
      fill (k);
      __asm__ volatile (LOAD_REGS "{insn}" SAVE_REGS
                        : [ri] "+r" (ri), [ro] "+r" (ro) : : CLOBBERS);
      c = crc_bytes (c, regs_out, 64);
    }}
  return c;
}}''')
    tests.append((name, insn))

# structure loads and stores
lists = {
    2: ['{d16, d17}', '{d16, d18}', '{d16-d19}'],
    4: ['{d16-d19}', '{d16, d18, d20, d22}'],
}
aligns = {
    ('{d16, d17}', 2): [':64', ':128'],
    ('{d16, d18}', 2): [':64', ':128'],
    ('{d16-d19}', 2): [':64', ':128', ':256'],
    ('{d16-d19}', 4): [':64', ':128', ':256'],
    ('{d16, d18, d20, d22}', 4): [':64', ':128', ':256'],
}
n = 0
for ld in (True, False):
    for nst in (2, 4):
        for sz in ('8', '16'):
            for rl in lists[nst]:
                for al in [''] + aligns[(rl, nst)]:
                    for wb in ('', '!', ', %[rm]'):
                        op = ('vld' if ld else 'vst') + f'{nst}.{sz}'
                        insn = f'{op} {rl}, [%[p]{al}]{wb if wb != ", %[rm]" else ""}{wb if wb == ", %[rm]" else ""}'
                        insn = insn.replace(']!', ']!').replace('], %[rm]', '], %[rm]')
                        name = f'ldst{n}'
                        n += 1
                        offs = '0, 32' if al else '0, 1, 3, 8, 32, 37'
                        mem = 'src' if ld else 'dst'
                        w(f'''
static uint32_t {name} (void)
{{
  static const int offs[] = {{ {offs} }};
  uint32_t c = 0;
  for (unsigned k = 0; k < sizeof offs / sizeof offs[0]; k++)
    {{
      uint8_t *ri = regs_in, *ro = regs_out, *p = {mem} + offs[k];
      int32_t rm = 5 + (int) k;
      fill (k + 100);
      __asm__ volatile (LOAD_REGS "{insn}" SAVE_REGS
                        : [ri] "+r" (ri), [ro] "+r" (ro), [p] "+r" (p)
                        : [rm] "r" (rm) : CLOBBERS);
      c = crc_bytes (c, regs_out, 64);
      c = crc_bytes (c, dst, sizeof dst);
      int32_t moved = p - ({mem} + offs[k]);
      c = crc_bytes (c, &moved, 4);
    }}
  return c;
}}''')
                        tests.append((name, insn.replace('%[p]', 'p').replace('%[rm]', 'rm')))

w('''
static const struct { const char *name; uint32_t (*fn) (void); } tests[] = {''')
for name, insn in tests:
    w(f'  {{ "{insn}", {name} }},')
w('''};

int main (int argc, char **argv)
{
  int verbose = argc > 1 && !strcmp (argv[1], "-v");
  uint32_t c = 0;
  crc_init ();
  for (unsigned t = 0; t < sizeof tests / sizeof tests[0]; t++)
    {
      uint32_t r = tests[t].fn ();
      if (verbose)
        printf ("%-44s %08x\\n", tests[t].name, r);
      c = crc_bytes (c, &r, 4);
    }
  printf ("t_neonperm: %u forms, CRC %08x\\n",
          (unsigned) (sizeof tests / sizeof tests[0]), c);
  return 0;
}''')

here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, 'programs', 't_neonperm.c'), 'w') as f:
    f.write('\n'.join(out) + '\n')
print(len(tests), 'forms')
